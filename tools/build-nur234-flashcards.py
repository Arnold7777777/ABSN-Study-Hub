BULLET = re.compile(r'^\s*(?:[-•*·–]+|\d+[.)]|[A-Z]\))\s*')


def answer(text):
    """Her answers are short lines; runs of bulleted lines become a list."""
    out, items = [], []

    def flush():
        if items:
            out.append('<ul>' + ''.join('<li>%s</li>' % i for i in items) + '</ul>')
            items.clear()
    for raw in text.split('\n'):
        line = raw.strip().replace('**', '')
        if not line:
            flush()
            continue
        if BULLET.match(line) and not re.match(r'^\d+[.)]?\s*(cm|%|bpm|mm)', line):
            item = BULLET.sub('', line, count=1).strip()
            if item:
                items.append(html.escape(item, quote=False))
            continue
        flush()
        cls = ' class="arrow"' if line in ('↓', '→') else ''
        out.append('<p%s>%s</p>' % (cls, html.escape(line, quote=False)))
    flush()
    return '\n'.join(out)


def build():
    d = json.load(io.open(DATA, encoding='utf-8'))
    cards = d['cards']
    total = len(cards)
    body = []
    chips = ['<button type="button" class="chip on" data-m="all" aria-pressed="true">All modules <b>%d</b></button>' % total]
    for m, (href, name) in MODULES.items():
        n = sum(1 for c in cards if c['m'] == m)
        chips.append('<button type="button" class="chip" data-m="%d" aria-pressed="false">Module %d <b>%d</b></button>' % (m, m, n))
    for m, (href, name) in MODULES.items():
        mine = [c for c in cards if c['m'] == m]
        secs = []
        for c in mine:
            if c['sec'] not in secs:
                secs.append(c['sec'])
        body.append('<section class="mod" data-m="%d" id="m%d">' % (m, m))
        body.append('<h2><span class="mn">M%d</span>%s <span class="ct">%d cards</span></h2>' % (m, name, len(mine)))
        body.append('<p class="modlink"><a href="%s">Open the Module %d page</a></p>' % (href, m))
        for s in secs:
            these = [c for c in mine if c['sec'] == s]
            body.append('<h3>%s <span class="ct">%d</span></h3>' % (html.escape(s), len(these)))
            body.append('<div class="deck">')
            for c in these:
                note = ('<p class="fix">&#9989; %s</p>' % html.escape(c['note'], quote=False)) if c.get('note') else ''
                body.append('<details class="fc" id="%s"><summary>%s</summary><div class="fa">%s%s</div></details>'
                            % (c['id'], html.escape(c['q'], quote=False), answer(c['a']), note))
            body.append('</div>')
        body.append('</section>')
    return TEMPLATE.replace('{{TOTAL}}', str(total)).replace('{{CHIPS}}', ''.join(chips)).replace('{{BODY}}', '\n'.join(body))


